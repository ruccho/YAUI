using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace Yaui.Editor
{
    /// <summary>The inspector of <see cref="YauiShaderSettings"/>, with the generation of the uber shader.</summary>
    [CustomEditor(typeof(YauiShaderSettings))]
    internal sealed class YauiShaderSettingsEditor : UnityEditor.Editor
    {
        public override void OnInspectorGUI()
        {
            base.OnInspectorGUI();
            EditorGUILayout.Space();
            EditorGUILayout.HelpBox(
                "Generate the uber shader after changing the modules. Modules are numbered by their position in the list.",
                MessageType.Info);
            if (GUILayout.Button("Generate Uber Shader"))
                YauiUberShaderGenerator.Generate((YauiShaderSettings)target);
        }
    }

    /// <summary>
    /// Writes the uber shader of a <see cref="YauiShaderSettings"/>: YAUI's Uber.shader with the keyword YAUI_MODULE,
    /// the includes of the modules, and <c>YauiModuleFrag</c>, which calls the module of a primitive by its id.
    /// </summary>
    public static class YauiUberShaderGenerator
    {
        private const string SourcePath = "Packages/com.ruccho.yaui/Runtime/Resources/Yaui/Uber.shader";
        private const string Include = "#include \"Packages/com.ruccho.yaui/Runtime/Shaders/Yaui.hlsl\"";

        /// <summary>The path of the generated shader: the settings' shader, or next to the settings.</summary>
        public static string PathOf(YauiShaderSettings settings)
        {
            if (settings.UberShader != null) return AssetDatabase.GetAssetPath(settings.UberShader);

            var directory = Path.GetDirectoryName(AssetDatabase.GetAssetPath(settings));
            return (directory + "/YauiUberModules.shader").Replace('\\', '/');
        }

        public static string GenerateText(YauiShaderSettings settings)
        {
            var source = File.ReadAllText(Path.GetFullPath(SourcePath));
            var name = source.IndexOf("\"Hidden/Yaui/Uber\"", System.StringComparison.Ordinal);
            if (name < 0 || source.IndexOf(Include, System.StringComparison.Ordinal) < 0)
                throw new System.InvalidOperationException("Uber.shader does not have the expected layout.");

            var modules = new StringBuilder();
            modules.AppendLine("#pragma multi_compile_local _ YAUI_MODULE");
            modules.AppendLine("    #define YAUI_MODULES");
            modules.AppendLine("    " + Include);
            var dispatch = new StringBuilder();
            dispatch.AppendLine("    #if defined(YAUI_MODULE)");
            for (var i = 0; i < settings.Modules.Count && i < YauiPrimitive.MaxModuleId; i++)
            {
                var module = settings.Modules[i];
                if (module == null) continue;

                modules.AppendLine("    #include \"" + module.IncludePath + "\"");
            }

            dispatch.AppendLine("    half4 YauiModuleFrag(uint module, Varyings i, bool world)");
            dispatch.AppendLine("    {");
            dispatch.AppendLine("        [branch] switch (module)");
            dispatch.AppendLine("        {");
            for (var i = 0; i < settings.Modules.Count && i < YauiPrimitive.MaxModuleId; i++)
            {
                var module = settings.Modules[i];
                if (module == null) continue;

                dispatch.AppendLine("            case " + (i + 1) + "u: return " + module.FunctionName + "(i, world); // " +
                                    module.Key);
            }

            dispatch.AppendLine("            default: return 0;");
            dispatch.AppendLine("        }");
            dispatch.AppendLine("    }");
            dispatch.AppendLine("    #endif");

            var text = source
                .Replace("\"Hidden/Yaui/Uber\"", "\"Hidden/Yaui/Uber (Modules)\"")
                .Replace(Include, modules.ToString().TrimEnd() + "\n" + dispatch.ToString().TrimEnd());
            text = "// Generated by YAUI from Uber.shader and the modules of " +
                   Path.GetFileName(AssetDatabase.GetAssetPath(settings)) + ". Do not edit; generate it again.\n" + text;
            // The line endings of Uber.shader throughout.
            text = text.Replace("\r\n", "\n");
            return source.Contains("\r\n") ? text.Replace("\n", "\r\n") : text;
        }

        public static void Generate(YauiShaderSettings settings)
        {
            var path = PathOf(settings);
            File.WriteAllText(Path.GetFullPath(path), GenerateText(settings));
            AssetDatabase.ImportAsset(path, ImportAssetOptions.ForceUpdate);
            settings.UberShader = AssetDatabase.LoadAssetAtPath<Shader>(path);
            EditorUtility.SetDirty(settings);
            AssetDatabase.SaveAssetIfDirty(settings);
            YauiShaderModules.Reload();
            Debug.Log("YAUI: generated " + path + " with " + settings.Modules.Count + " module(s).");
        }
    }
}
